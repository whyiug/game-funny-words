const legacyEntries = Object.values(WORD_DB)
  .flatMap((category) => category.items)
  .reduce((map, item) => {
    map.set(item.t.toLowerCase(), item);
    return map;
  }, new Map());

function capitalize(word) {
  return word
    .split(" ")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function toEntry(theme, [english, zh, zhPron]) {
  const displayWord = capitalize(english);
  const legacy = legacyEntries.get(displayWord.toLowerCase());

  return {
    t: displayWord,
    e: legacy?.e || theme.emoji,
    p: legacy?.p || "",
    zh,
    zhPron,
    catColor: theme.color,
    catLabel: theme.label,
  };
}

function createTheme(id, label, color, emoji, items) {
  return {
    id,
    label,
    color,
    emoji,
    items: items.map((item) => toEntry({ label, color, emoji }, item)),
  };
}

