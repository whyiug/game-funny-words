function combineThemes(id, label, themeKeys) {
  const seen = new Set();
  const items = themeKeys
    .flatMap((key) => THEMES[key].items)
    .filter((item) => {
      const entryKey = item.t.toLowerCase();
      if (seen.has(entryKey)) {
        return false;
      }

      seen.add(entryKey);
      return true;
    });

  return {
    id,
    label,
    type: "builtin",
    items,
  };
}

